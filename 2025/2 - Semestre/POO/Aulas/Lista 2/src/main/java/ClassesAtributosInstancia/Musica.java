package ClassesAtributosInstancia;

public class Musica {
    String nome;
    String artista;
    int duracaoEmSegundos;

    Musica (String nome, String artista, int duracaoEmSegundos) {
        this.nome = nome;
        this.artista = artista;
        this.duracaoEmSegundos = duracaoEmSegundos;
    }
}

package ModelagemConceitos;

public class Conta {
//    Atributos:
//
//    numero_conta: (String ou Int) O identificador único da conta.
//
//            agencia: (String ou Int) O número da agência à qual a conta pertence.
//
//            saldo: (Float ou Decimal) O valor monetário atual disponível na conta.
//
//            titular: (String ou um objeto do tipo Cliente) O nome do proprietário da conta.
//
//            limite_cheque_especial: (Float ou Decimal) O valor de crédito pré-aprovado que o titular pode usar além do saldo.
//
//            Métodos:
//
//    depositar(valor): Adiciona uma quantia especificada ao saldo da conta.
//
//    sacar(valor): Remove uma quantia do saldo, verificando se há fundos suficientes (incluindo o limite do cheque especial).
//
//    transferir(conta_destino, valor): Move uma quantia da conta atual para outra conta.
//
//            consultar_saldo(): Retorna o valor atual do saldo.
//
//            emitir_extrato(): Exibe o histórico de transações recentes da conta.
}
